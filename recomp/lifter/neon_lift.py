"""NEON lifting: emits calls to the helpers in neon.c (and inline copies for the common vld1/vst1)."""
import re
from capstone import arm as A

OPS = ['ADD', 'SUB', 'MUL', 'AND', 'ORR', 'EOR', 'BIC', 'ORN', 'MIN', 'MAX', 'ABD', 'HADD', 'RHADD', 'QADD', 'CGT', 'CGE', 'CEQ', 'TST',
       'CLT', 'CLE', 'SHLR', 'MLA', 'MLS', 'PMAX', 'PMIN', 'NEG', 'ABS', 'MVN', 'REV64', 'SHLI', 'SHR', 'SRA', 'LADD', 'LSUB', 'LABD',
       'LMUL', 'LMLA', 'LMLS', 'WADD', 'WSUB', 'NMOV', 'NSHR', 'NADDH', 'IMOV', 'IMVN', 'IORR', 'IBIC', 'ZIP', 'UZP', 'TRN', 'BSL',
       'BIT', 'BIF', 'CVT_F2S', 'CVT_F2U', 'CVT_S2F', 'CVT_U2F']
OPN = {n: i for i, n in enumerate(OPS)}


def emit_header(path):
    with open(path, 'w') as f:
        f.write('/* generated by neon_lift.py */\n#ifndef NEON_OPS_H\n#define NEON_OPS_H\n')
        for i, n in enumerate(OPS):
            f.write('#define N_%s %d\n' % (n, i))
        f.write('''#include "armrt.h"
void n_bin(CPU *c, int op, int esz, int kind, int d, int n, int m, int nb, int lane);
void n_un(CPU *c, int op, int esz, int kind, int d, int m, int nb);
void n_shi(CPU *c, int op, int esz, int kind, int d, int m, int nb, int imm);
void n_long(CPU *c, int op, int esz, int kind, int d, int n, int m, int lane);
void n_movl(CPU *c, int esz, int kind, int d, int m);
void n_narrow(CPU *c, int op, int esz, int d, int n, int m, int imm);
void n_imm(CPU *c, int op, int d, int nb, uint64_t imm, int esz);
void n_dup(CPU *c, int d, int nb, int esz, uint32_t val);
void n_dupl(CPU *c, int d, int nb, int esz, int s, int lane);
uint32_t n_getlane(CPU *c, int d, int esz, int sg, int lane);
void n_setlane(CPU *c, int d, int esz, int lane, uint32_t v);
void n_ext(CPU *c, int d, int n, int m, int nb, int boff);
void n_perm(CPU *c, int op, int esz, int d, int m, int nb);
void n_swp(CPU *c, int d, int m, int nb);
void n_tbl(CPU *c, int d, int first, int nregs, int m, int ext);
void n_bsel(CPU *c, int op, int d, int n, int m, int nb);
void n_cvt(CPU *c, int mode, int d, int m, int nb, int fbits);
void n_ldst(CPU *c, int store, int n, int esz, const int *R, int nR, uint32_t addr);
#endif
''')


from common import REGN, Unsupported


def _unsup(msg):
    raise Unsupported(msg)


def dn(L, o):
    """(D register index, class) of a vector register operand; Q registers map to their first D"""
    k, n = L.fp(L.cs.reg_name(o.reg))
    if k == 's':
        _unsup('vector op on s register')
    return (2 * n if k == 'q' else n), k


def nbytes(L, o):
    return 16 if L.cs.reg_name(o.reg)[0] == 'q' else 8


def lane_of(L, ins, o):
    """lane index of a d<N>[x] operand (capstone does not always fill vector_index)"""
    if o.vector_index >= 0:
        return o.vector_index
    m = re.search(r'%s\[(\d+)\]' % L.cs.reg_name(o.reg), ins.op_str)
    return int(m.group(1)) if m else -1


def imm_of(ins, default):
    m = re.search(r'#(0x[0-9a-fA-F]+|\d+)', ins.op_str)
    return int(m.group(1), 0) if m else default


def dtype(mn):
    parts = mn.split('.')
    suf = parts[1] if len(parts) > 1 else ''
    m = re.match(r'([a-z]?)(\d+)$', suf)
    if not m:
        return 4, 0
    t, bits = m.group(1), int(m.group(2))
    return bits // 8, (2 if t == 'f' else 1 if t == 's' else 0)


def dtype_last(mn):
    parts = mn.split('.')
    m = re.match(r'([a-z]?)(\d+)$', parts[-1])
    return (int(m.group(2)) // 8, 2 if m.group(1) == 'f' else 1 if m.group(1) == 's' else 0) if m else (4, 0)


BIN = {'vadd': 'ADD', 'vsub': 'SUB', 'vmul': 'MUL', 'vand': 'AND', 'vorr': 'ORR', 'veor': 'EOR', 'vbic': 'BIC', 'vorn': 'ORN',
       'vmin': 'MIN', 'vmax': 'MAX', 'vabd': 'ABD', 'vhadd': 'HADD', 'vrhadd': 'RHADD', 'vqadd': 'QADD', 'vcgt': 'CGT',
       'vcge': 'CGE', 'vceq': 'CEQ', 'vtst': 'TST', 'vclt': 'CLT', 'vcle': 'CLE', 'vmla': 'MLA', 'vmls': 'MLS',
       'vpmax': 'PMAX', 'vpmin': 'PMIN'}
LONG = {'vaddl': 'LADD', 'vsubl': 'LSUB', 'vabdl': 'LABD', 'vmull': 'LMUL', 'vmlal': 'LMLA', 'vmlsl': 'LMLS', 'vaddw': 'WADD', 'vsubw': 'WSUB'}


def h_bin(L, ins, nm, X):
    ops = ins.operands
    mn = ins.mnemonic
    esz, kind = dtype(mn)
    if len(ops) == 2:     # vorr/vbic style two-operand imm or tied
        ops = [ops[0], ops[0], ops[1]]
    d, _ = dn(L, ops[0])
    nb = nbytes(L, ops[0])
    # immediate forms of vorr/vbic: vorr.i32 qd, #imm
    if ops[-1].type == A.ARM_OP_IMM and nm in ('vorr', 'vbic') and len(ins.operands) == 2:
        op = 'IORR' if nm == 'vorr' else 'IBIC'
        e = esz
        imm = imm_of(ins, ops[-1].imm) & ((1 << (8 * e)) - 1)
        X.L.append('n_imm(c, N_%s, %d, %d, 0x%xull, %d);' % (op, d, nb, imm, e))
        return
    n, _ = dn(L, ops[1])
    lane = -1
    if ops[2].type == A.ARM_OP_IMM:      # compare against #0
        m = -1
    else:
        m, _ = dn(L, ops[2])
        lane = lane_of(L, ins, ops[2])
    if nm == 'vshl' and ops[2].type != A.ARM_OP_IMM:
        # vshl.<dt> qd, qm(value), qn(shift)
        X.L.append('n_bin(c, N_SHLR, %d, %d, %d, %d, %d, %d, -1);' % (esz, kind, d, n, m, nb))
        return
    X.L.append('n_bin(c, N_%s, %d, %d, %d, %d, %d, %d, %d);' % (BIN[nm], esz, kind, d, n, m, nb, lane))


def h_long(L, ins, nm, X):
    ops = ins.operands
    esz, kind = dtype(ins.mnemonic)
    d, _ = dn(L, ops[0]); n, _ = dn(L, ops[1]); m, _ = dn(L, ops[2])
    lane = lane_of(L, ins, ops[2])
    X.L.append('n_long(c, N_%s, %d, %d, %d, %d, %d, %d);' % (LONG[nm], esz, kind, d, n, m, lane))


def h_unary(L, ins, nm, X):
    ops = ins.operands
    esz, kind = dtype(ins.mnemonic)
    d, _ = dn(L, ops[0]); m, _ = dn(L, ops[1])
    if ops[1].type == A.ARM_OP_IMM:
        _unsup('unary imm')
    op = {'vneg': 'NEG', 'vabs': 'ABS', 'vmvn': 'MVN', 'vrev64': 'REV64'}[nm]
    if nm == 'vmvn' and ops[1].type == A.ARM_OP_IMM:
        pass
    X.L.append('n_un(c, N_%s, %d, %d, %d, %d, %d);' % (op, esz, kind, d, m, nbytes(L, ops[0])))


def h_vmvn(L, ins, nm, X):
    ops = ins.operands
    if ops[1].type == A.ARM_OP_IMM:
        esz, _ = dtype(ins.mnemonic)
        d, _ = dn(L, ops[0])
        X.L.append('n_imm(c, N_IMVN, %d, %d, 0x%xull, %d);' % (d, nbytes(L, ops[0]), imm_of(ins, ops[1].imm) & ((1 << (8 * esz)) - 1), esz))
    else:
        h_unary(L, ins, nm, X)


def h_shift(L, ins, nm, X):
    ops = ins.operands
    esz, kind = dtype(ins.mnemonic)
    d, _ = dn(L, ops[0]); m, _ = dn(L, ops[1])
    nb = nbytes(L, ops[0])
    if ops[2].type != A.ARM_OP_IMM:
        return h_bin(L, ins, nm, X)
    imm = ops[2].imm
    op = {'vshl': 'SHLI', 'vshr': 'SHR', 'vsra': 'SRA'}[nm]
    X.L.append('n_shi(c, N_%s, %d, %d, %d, %d, %d, %d);' % (op, esz, kind, d, m, nb, imm))


def h_movl(L, ins, nm, X):
    ops = ins.operands
    esz, kind = dtype(ins.mnemonic)
    d, _ = dn(L, ops[0]); m, _ = dn(L, ops[1])
    X.L.append('n_movl(c, %d, %d, %d, %d);' % (esz, kind, d, m))


def h_narrow(L, ins, nm, X):
    ops = ins.operands
    esz, kind = dtype(ins.mnemonic)       # source element size
    d, _ = dn(L, ops[0])
    if nm == 'vmovn':
        m, _ = dn(L, ops[1])
        X.L.append('n_narrow(c, N_NMOV, %d, %d, %d, %d, 0);' % (esz, d, m, m))
    elif nm == 'vshrn':
        m, _ = dn(L, ops[1])
        X.L.append('n_narrow(c, N_NSHR, %d, %d, %d, %d, %d);' % (esz, d, m, m, ops[2].imm))
    else:   # vaddhn
        n, _ = dn(L, ops[1]); m, _ = dn(L, ops[2])
        X.L.append('n_narrow(c, N_NADDH, %d, %d, %d, %d, 0);' % (esz, d, n, m))


def h_vdup(L, ins, nm, X):
    ops = ins.operands
    esz, _ = dtype(ins.mnemonic)
    d, _ = dn(L, ops[0])
    nb = nbytes(L, ops[0])
    if ops[1].type == A.ARM_OP_REG and L.cs.reg_name(ops[1].reg) in REGN:
        X.L.append('n_dup(c, %d, %d, %d, %s);' % (d, nb, esz, L.rv(ops[1].reg, X)))
    else:
        s, _ = dn(L, ops[1])
        X.L.append('n_dupl(c, %d, %d, %d, %d, %d);' % (d, nb, esz, s, lane_of(L, ins, ops[1])))


def h_ext(L, ins, nm, X):
    ops = ins.operands
    esz, _ = dtype(ins.mnemonic)
    d, _ = dn(L, ops[0]); n, _ = dn(L, ops[1]); m, _ = dn(L, ops[2])
    X.L.append('n_ext(c, %d, %d, %d, %d, %d);' % (d, n, m, nbytes(L, ops[0]), ops[3].imm * esz))


def h_perm(L, ins, nm, X):
    ops = ins.operands
    esz, _ = dtype(ins.mnemonic)
    d, _ = dn(L, ops[0]); m, _ = dn(L, ops[1])
    op = {'vzip': 'ZIP', 'vuzp': 'UZP', 'vtrn': 'TRN'}[nm]
    X.L.append('n_perm(c, N_%s, %d, %d, %d, %d);' % (op, esz, d, m, nbytes(L, ops[0])))


def h_vswp(L, ins, nm, X):
    ops = ins.operands
    d, _ = dn(L, ops[0]); m, _ = dn(L, ops[1])
    X.L.append('n_swp(c, %d, %d, %d);' % (d, m, nbytes(L, ops[0])))


def h_vtbl(L, ins, nm, X):
    ops = ins.operands
    d, _ = dn(L, ops[0])
    regs = [dn(L, o)[0] for o in ops[1:-1]]
    m, _ = dn(L, ops[-1])
    X.L.append('n_tbl(c, %d, %d, %d, %d, %d);' % (d, regs[0], len(regs), m, 1 if nm == 'vtbx' else 0))


def h_bsel(L, ins, nm, X):
    ops = ins.operands
    d, _ = dn(L, ops[0]); n, _ = dn(L, ops[1]); m, _ = dn(L, ops[2])
    X.L.append('n_bsel(c, N_%s, %d, %d, %d, %d);' % (nm[1:].upper(), d, n, m, nbytes(L, ops[0])))


def vcvt(L, ins, nm, X):
    ops = ins.operands
    mn = ins.mnemonic.split('.')
    dt, st = mn[1], mn[2]
    mode = {('s32', 'f32'): 'F2S', ('u32', 'f32'): 'F2U', ('f32', 's32'): 'S2F', ('f32', 'u32'): 'U2F'}.get((dt, st))
    if mode is None:
        _unsup('neon vcvt ' + ins.mnemonic)
    d, _ = dn(L, ops[0]); m, _ = dn(L, ops[1])
    fb = ops[2].imm if len(ops) > 2 and ops[2].type == A.ARM_OP_IMM else 0
    X.L.append('n_cvt(c, N_CVT_%s, %d, %d, %d, %d);' % (mode, d, m, nbytes(L, ops[0]), fb))


def arith(L, ins, nm, X):
    """NEON form of vadd/vsub/vmul/vmla/vmls/vneg/vabs (called from the VFP arithmetic handler)"""
    if nm in ('vneg', 'vabs'):
        return h_unary(L, ins, nm, X)
    return h_bin(L, ins, nm, X)


def vmov(L, ins, nm, X):
    ops = ins.operands
    mn = ins.mnemonic
    esz, kind = dtype(mn)
    o0 = ops[0]
    iscore = lambda o: o.type == A.ARM_OP_REG and L.cs.reg_name(o.reg) in REGN
    if len(ops) == 2 and o0.type == A.ARM_OP_REG and not iscore(o0):
        d, _ = dn(L, o0)
        if lane_of(L, ins, o0) >= 0 and iscore(ops[1]):               # vmov.<sz> dd[x], rt
            X.L.append('n_setlane(c, %d, %d, %d, %s);' % (d, esz, lane_of(L, ins, o0), L.rv(ops[1].reg, X)))
            return
        nb = nbytes(L, o0)
        if ops[1].type == A.ARM_OP_IMM:
            e = esz
            imm = imm_of(ins, ops[1].imm) & (0xffffffffffffffff if e == 8 else (1 << (8 * e)) - 1)
            X.L.append('n_imm(c, N_IMOV, %d, %d, 0x%xull, %d);' % (d, nb, imm, e))
            return
        if ops[1].type == A.ARM_OP_FP:
            import struct
            bits = struct.unpack('<I', struct.pack('<f', ops[1].fp))[0]
            X.L.append('n_imm(c, N_IMOV, %d, %d, 0x%xull, 4);' % (d, nb, bits))
            return
        if ops[1].type == A.ARM_OP_REG and not iscore(ops[1]):
            m, _ = dn(L, ops[1])
            X.L.append('memcpy(c->f.b + %d, c->f.b + %d, %d);' % (8 * d, 8 * m, nb))
            return
    if len(ops) == 2 and iscore(o0) and ops[1].type == A.ARM_OP_REG and lane_of(L, ins, ops[1]) >= 0:     # vmov.<t> rt, dn[x]
        s, _ = dn(L, ops[1])
        sg = 1 if mn.split('.')[1].startswith('s') else 0
        if esz == 4:
            X.L.append('R(%d) = n_getlane(c, %d, 4, 0, %d);' % (L.rn(o0.reg), s, lane_of(L, ins, ops[1])))
        else:
            X.L.append('R(%d) = n_getlane(c, %d, %d, %d, %d);' % (L.rn(o0.reg), s, esz, sg, lane_of(L, ins, ops[1])))
        return
    _unsup('neon vmov ' + mn)


def h_vldst(L, ins, nm, X):
    ops = ins.operands
    store = nm.startswith('vst')
    n = int(nm[3])
    esz, _ = dtype(ins.mnemonic)
    mi = next(i for i, o in enumerate(ops) if o.type == A.ARM_OP_MEM)
    regs = ops[:mi]
    base = L.rn(ops[mi].mem.base)
    post = ops[mi + 1] if mi + 1 < len(ops) else None
    X.L.append('t0 = R(%d);' % base)
    lane0 = lane_of(L, ins, regs[0])
    if lane0 >= 0:                    # single lane
        if n != 1 or len(regs) != 1:
            _unsup('lane ' + nm)
        d, _ = dn(L, regs[0])
        off = 8 * d + lane0 * esz
        if store:
            X.L.append('memcpy(GP(t0), c->f.b + %d, %d);' % (off, esz))
        else:
            X.L.append('memcpy(c->f.b + %d, GP(t0), %d);' % (off, esz))
        total = esz * n
    elif '[]' in ins.op_str:
        if n != 1:
            _unsup('all-lanes ' + nm)
        ld = {1: 'ld8', 2: 'ld16', 4: 'ld32'}[esz]
        X.L.append('t2 = %s(t0);' % ld)
        for o in regs:
            d, _ = dn(L, o)
            X.L.append('n_dup(c, %d, 8, %d, t2);' % (d, esz))
        total = esz
    else:
        R = [dn(L, o)[0] for o in regs]
        total = 8 * len(R)
        if n == 1 and all(R[i + 1] == R[i] + 1 for i in range(len(R) - 1)):
            if store:
                X.L.append('memcpy(GP(t0), c->f.b + %d, %d);' % (8 * R[0], total))
            else:
                X.L.append('memcpy(c->f.b + %d, GP(t0), %d);' % (8 * R[0], total))
        else:
            X.L.append('{ static const int rl[] = { %s }; n_ldst(c, %d, %d, %d, rl, %d, t0); }' % (', '.join(map(str, R)), 1 if store else 0, n, esz, len(R)))
    if ins.writeback or (post is not None and post.type == A.ARM_OP_REG):
        if post is not None and post.type == A.ARM_OP_REG:
            X.L.append('R(%d) = t0 + %s;' % (base, L.rv(post.reg, X)))
        else:
            X.L.append('R(%d) = t0 + %d;' % (base, total))


def handler(L, nm):
    if nm in BIN or nm == 'vshl':
        if nm == 'vshl':
            return h_shift
        if nm in ('vorr', 'vbic') or True:
            return h_bin
    if nm in LONG: return h_long
    if nm in ('vneg', 'vabs', 'vrev64'): return h_unary
    if nm == 'vmvn': return h_vmvn
    if nm in ('vshr', 'vsra'): return h_shift
    if nm == 'vmovl': return h_movl
    if nm in ('vmovn', 'vshrn', 'vaddhn'): return h_narrow
    if nm == 'vdup': return h_vdup
    if nm == 'vext': return h_ext
    if nm in ('vzip', 'vuzp', 'vtrn'): return h_perm
    if nm == 'vswp': return h_vswp
    if nm in ('vtbl', 'vtbx'): return h_vtbl
    if nm in ('vbsl', 'vbit', 'vbif'): return h_bsel
    if re.match(r'v(ld|st)[1-4]$', nm): return h_vldst
    return None
